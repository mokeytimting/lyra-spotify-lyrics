/** 把伺服器的錯誤代碼／訊息轉成目前介面語言的說明 */
export function localizeServerError(code: string | undefined, message?: string): string {
  if (message && message.includes('Client ID')) return tApp('errClientId');
  if (message && message.includes('Base URL')) return tApp('errBaseUrl');
  switch (code) {
    case 'NO_ENGINE':
      return tApp('errNoEngine');
    case 'BAD_KEY':
      return tApp('errBadKey');
    case 'QUOTA':
      return tApp('errQuota');
    case 'BAD_REQUEST':
      return tApp('errBadRequest');
    case 'UPSTREAM':
      return tApp('errUpstream');
    default:
      // 不認得的錯誤：保留原本的訊息
      return message || tApp('errUpstream');
  }
}
